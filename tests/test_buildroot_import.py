def test_import_is_best_effort_and_keeps_network_source(tmp_path):
    paths = _project(tmp_path)
    console = io.StringIO()
    summary = import_buildroot_packages(paths, console=console)

    assert summary.imported == 1
    assert summary.skipped == 1
    assert summary.failed == 1
    package_dir = tmp_path / "packages" / "foo"
    assert not (package_dir / "source").exists()
    package = yaml.safe_load((package_dir / "package.yaml").read_text(encoding="utf-8"))
    assert package["source"]["url"] == "https://example.org/foo/foo-1.2.3.tar.gz"
    assert package["source"]["sha256"] == "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"
    assert package["source"]["allow_unverified"] is False
    assert 'source "packages/foo/Kconfig"' in (tmp_path / "packages" / "Kconfig").read_text(encoding="utf-8")
    assert "Buildroot import" not in (package_dir / "Kconfig").read_text(encoding="utf-8")
    assert "# Generated by smart-build package metadata." in (package_dir / "Kconfig").read_text(encoding="utf-8")
    assert package["description"] == "A tiny foo library used in import tests"
    kconfig = (package_dir / "Kconfig").read_text(encoding="utf-8")
    assert 'bool "foo - A tiny foo library used in import tests"' in kconfig
    assert "A tiny foo library used in import tests" in kconfig
    assert "    help" in kconfig
    assert "failed: bad" in console.getvalue()
    metadata = normalize_package_metadata(load_description(package_dir / "package.yaml"))
    assert metadata.name == "foo"
    assert metadata.description == "A tiny foo library used in import tests"


