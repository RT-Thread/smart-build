class _Terminal(io.StringIO):
    def isatty(self):
        return True


def _project(tmp_path):
    buildroot = tmp_path / "buildroot"
    (buildroot / "package" / "foo").mkdir(parents=True)
    (buildroot / "package" / "existing").mkdir(parents=True)
    (buildroot / "Makefile").write_text("all:\n", encoding="utf-8")
    (buildroot / ".config").write_text(
        "BR2_PACKAGE_FOO=y\nBR2_PACKAGE_EXISTING=y\nBR2_PACKAGE_BAD=y\n",
        encoding="utf-8",
    )
    (buildroot / "package" / "foo" / "foo.mk").write_text(
        'FOO_VERSION = 1.2.3\nFOO_SITE = https://example.org/foo\n'
        'FOO_SOURCE = foo-1.2.3.tar.gz\n',
        encoding="utf-8",
    )
    (buildroot / "package" / "foo" / "foo.hash").write_text(
        "sha256 0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef foo-1.2.3.tar.gz\n",
        encoding="utf-8",
    )
    (buildroot / "package" / "foo" / "Config.in").write_text(
        'config BR2_PACKAGE_FOO\n'
        '    bool "foo library"\n'
        '    help\n'
        '      A tiny foo library used in import tests\n',
        encoding="utf-8",
    )
    (buildroot / "package" / "existing" / "existing.mk").write_text(
        'EXISTING_VERSION = 1.0\nEXISTING_SITE = https://example.org/existing\n'
        'EXISTING_SOURCE = existing.tar.gz\n',
        encoding="utf-8",
    )
    packages = tmp_path / "packages"
    existing = packages / "existing"
    existing.mkdir(parents=True)
    (existing / "package.yaml").write_text(
        "schema_version: 1\nkind: package\nname: existing\nversion: '1.0'\n"
        "type: executable\nsource:\n  directory: apps/hello\n"
        "build:\n  python:\n    script: sbuild.py\n    outputs: [/bin/existing]\ninstall:\n  path: /bin/existing\n",
        encoding="utf-8",
    )
    (existing / "sbuild.py").write_text("", encoding="utf-8")
    (packages / "Kconfig").write_text("# generated\n", encoding="utf-8")
    paths = BuildPaths.for_machine("test-machine", root=tmp_path)
    return paths


