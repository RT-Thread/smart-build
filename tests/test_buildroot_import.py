def test_buildroot_menuconfig_clones_missing_tree_then_continues(tmp_path):
    paths = BuildPaths.for_machine("test-machine", root=tmp_path)
    calls = []

    def runner(command, cwd, env):
        calls.append(command)
        if command[:2] == ["git", "clone"]:
            clone_dir = Path(command[-1])
            clone_dir.mkdir(parents=True)
            (clone_dir / "Makefile").write_text("all:\n", encoding="utf-8")
            return type("Completed", (), {"returncode": 0})()
        (paths.work_dir / "buildroot" / ".config").parent.mkdir(parents=True, exist_ok=True)
        (paths.work_dir / "buildroot" / ".config").write_text("BR2_PACKAGE_FOO=y\n", encoding="utf-8")
        return type("Completed", (), {"returncode": 0})()

    result = run_buildroot_menuconfig(paths, command_runner=runner, confirm_runner=lambda path: True)

    assert result == paths.work_dir / "buildroot" / ".config"
    assert (tmp_path / "buildroot" / "Makefile").is_file()
    assert not (tmp_path / ".buildroot-clone").exists()
    assert calls[0][:4] == ["git", "clone", "--depth", "1"]
    assert calls[1][-1] == "menuconfig"


