    ownership = yaml.safe_load((never_import / "buildroot-ownership.yaml").read_text(encoding="utf-8"))
    symbols = ownership["symbols"]

    assert "BR2_PACKAGE_KEEP" in symbols
    assert "BR2_PACKAGE_MUSL" not in symbols
    assert "BR2_PACKAGE_CMAKE" not in symbols
    assert "BR2_PACKAGE_GONE" not in symbols


